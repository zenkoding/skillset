#!/usr/bin/env bash
# check-doc-rot.sh — fail if drift-prone specifics reappear in live harness docs.
# Rationale: counts and freshness stamps go stale; describe things qualitatively.
set -uo pipefail

# Live, evergreen, agent-facing harness docs. Point-in-time trees
# (research/briefs/designs/spikes/adrs/specs/investigations/_archive) are
# intentionally excluded — their dated/confidence headers are part of the record.
FILES=(
  AGENTS.md README.md CONTRIBUTING.md
)

# Forbidden patterns. Three groups:
#  1. Freshness stamps (precise; zero false-positive risk).
#  2. Heading/label component counts ("Skills (31)", "(33 Total)").
#  3. Permission-rule counts.
#  4. Prose component counts: number + up to 4 words (incl. '&') + noun. This is
#     the form that bit this session ("27 specialized agents"). Broad by design;
#     the ALLOWLIST below removes the single known legitimate collision.
# Deliberately NOT matching bare "confidence" — that is a real feature elsewhere.
PATTERNS='Last Updated:|Analysis Confidence:|Generated by .*Confidence: ?[0-9]|(Agents|Skills|Commands|Learned Tools) \([0-9]|[0-9]+ Total|[0-9]+\+? (allow|deny) rules|240\+|60\+ deny|[0-9]+( [A-Za-z&]+){0,4} (agents|skills|commands)'

# Known legitimate count-shaped prose (NOT component inventory). Keep minimal and
# documented; extend only with a comment explaining why the phrase is not rot.
ALLOWLIST='Wave [0-9]+ agents'

fail=0
for f in "${FILES[@]}"; do
  [ -f "$f" ] || continue
  matches=$(grep -nEH "$PATTERNS" "$f" | grep -vE "$ALLOWLIST" || true)
  if [ -n "$matches" ]; then
    echo "DOC ROT in $f:"
    echo "$matches"
    fail=1
  fi
done

if [ "$fail" -ne 0 ]; then
  echo ""
  echo "Doc rot detected. Harness docs must not hardcode counts or freshness stamps."
  echo "Describe components qualitatively; drop counts and freshness stamps."
  exit 1
fi
echo "check-doc-rot: OK — no drift-prone specifics in live harness docs."
